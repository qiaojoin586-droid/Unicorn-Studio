import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const read = file => fs.readFileSync(path.join(root, file), 'utf8').replaceAll('\r\n', '\n')
const brand = JSON.parse(read('shared/brand.json'))
const svg = read('shared/brand-mark.svg')
const css = '/* Generated by scripts/sync-design.mjs from shared/brand.json. */\n:root {\n' + Object.entries(brand).map(([key, value]) => `  --brand-${key}: ${value};`).join('\n') + '\n}\n'
const targets = new Map([
  ['frontend/src/generated/brand.css', css], ['admin/src/generated/brand.css', css],
  ['admin/src/generated/brand-mark.svg', svg.replaceAll('currentColor', brand.ink)],
  ['admin/src/generated/brand-mark-light.svg', svg.replaceAll('currentColor', brand.paper)],
  ['frontend/src/components/BrandMark.vue', '<!-- Generated from shared/brand-mark.svg by scripts/sync-design.mjs. -->\n<template>\n' + svg.replace(' xmlns="http://www.w3.org/2000/svg"', ' class="brand-mark" aria-hidden="true"').trim() + '\n</template>\n<style scoped>\n.brand-mark { display: block; width: 42px; height: 42px; flex-shrink: 0; }\n</style>\n'],
])
const drift = []
for (const [relative, value] of targets) {
  const file = path.join(root, relative)
  const current = fs.existsSync(file) ? fs.readFileSync(file, 'utf8').replaceAll('\r\n', '\n') : null
  if (current === value) continue
  if (process.argv.includes('--check')) drift.push(relative)
  else { fs.mkdirSync(path.dirname(file), { recursive: true }); fs.writeFileSync(file, value); console.log('Synced ' + relative) }
}
if (drift.length) { console.error('Shared design drift:\n' + drift.join('\n')); process.exitCode = 1 }
else if (process.argv.includes('--check')) console.log('Shared brand assets are synchronized.')
